// Контракт API имеет один источник; копия нужна без смены структуры сборки server/dist.
import { readFileSync, writeFileSync } from 'node:fs';
const source = new URL('../server/src/rift/protocol.ts', import.meta.url);
const destination = new URL('../client/src/game/core/rift.ts', import.meta.url);
const expected = '// Generated by scripts/sync-rift-contract.mjs. Не редактировать вручную.\n' + readFileSync(source, 'utf8');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== expected) throw new Error('Rift contract differs. Run: node scripts/sync-rift-contract.mjs');
  console.log('[OK] Rift client/server contract matches.');
} else writeFileSync(destination, expected);
